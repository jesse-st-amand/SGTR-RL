"""Tests for data extraction logic in scripts.prepare_data.

Focuses on properties that prevent silent data bugs:
- IND extraction must combine control + treatment records
- Extracted data must not be trivially solvable by label mapping
- Record fields are correctly populated
"""

import json
from pathlib import Path

from scripts.prepare_data import (
    _find_control_opponent,
    _run_all_extractions,
    run_extraction,
    sample_to_training_record,
)

# --- Fixtures: synthetic eval samples ---


def _make_ind_sample(
    uuid: str,
    is_control: bool,
    correct_answer: str,
    response_text: str = "Some response",
    dataset: str = "sharegpt",
    opponent: str = "qwen-2.5-7b",
):
    """Create a synthetic IND eval sample matching the Inspect format."""
    if is_control:
        treatment_name = "ll-3.1-8b"
    else:
        treatment_name = opponent

    # Simulate the label randomization from self-rec-framework:
    # correct_answer is which number means the right thing
    if correct_answer == "1":
        instruction = (
            'Answer "1" if this is your original output, or "2" if it was '
            "generated by a different language model."
        )
    else:
        instruction = (
            'Answer "2" if this is your original output, or "1" if it was '
            "generated by a different language model."
        )

    prompt = (
        f"Below is a user request followed by a response:\n\n"
        f"Request - \"test question\"\n\n"
        f"Response - \"{response_text}\"\n\n"
        f"Is this response your original output? {instruction} "
        f"Provide only the number and no additional text."
    )

    return {
        "input": prompt,
        "target": correct_answer,
        "metadata": {
            "uuid": uuid,
            "treatment_name": treatment_name,
            "is_control": is_control,
            "correct_answer": correct_answer,
            "dataset_name": dataset,
            "data_subset": "test_split",
        },
    }


def _make_pw_sample(
    uuid: str,
    correct_answer: str,
    opponent: str = "qwen-2.5-7b",
    dataset: str = "sharegpt",
):
    """Create a synthetic PW eval sample."""
    return {
        "input": f"Which response is yours? Answer {correct_answer}.",
        "target": correct_answer,
        "metadata": {
            "uuid": uuid,
            "treatment_name_1": "ll-3.1-8b",
            "treatment_name_2": opponent,
            "correct_answer": correct_answer,
            "dataset_name": dataset,
            "data_subset": "test_split",
        },
    }


def _write_eval_dir(tmp_path: Path, samples: list[dict], name: str = "eval1") -> Path:
    """Write synthetic samples to an eval directory structure."""
    eval_dir = tmp_path / name
    samples_dir = eval_dir / "samples"
    samples_dir.mkdir(parents=True)
    for i, sample in enumerate(samples):
        with open(samples_dir / f"{i}_epoch_1.json", "w") as f:
            json.dump(sample, f)
    return eval_dir


# --- Tests for sample_to_training_record ---


class TestSampleToTrainingRecord:
    def test_ind_treatment_has_is_control_false(self):
        sample = _make_ind_sample("id1", is_control=False, correct_answer="1")
        record = sample_to_training_record(sample)
        assert record["is_control"] is False
        assert record["format"] == "ind"

    def test_ind_control_has_is_control_true(self):
        sample = _make_ind_sample("id1", is_control=True, correct_answer="2")
        record = sample_to_training_record(sample)
        assert record["is_control"] is True
        assert record["format"] == "ind"

    def test_ind_preserves_dataset(self):
        sample = _make_ind_sample("id1", is_control=False, correct_answer="1",
                                  dataset="wikisum")
        record = sample_to_training_record(sample)
        assert record["dataset"] == "wikisum"
        assert record["data_subset"] == "test_split"

    def test_pw_has_no_is_control(self):
        sample = _make_pw_sample("id1", "1")
        record = sample_to_training_record(sample)
        assert "is_control" not in record
        assert record["format"] == "pw"


